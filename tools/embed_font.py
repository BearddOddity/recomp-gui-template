#!/usr/bin/env python3
"""Turn a TTF into src/gui_font_montserrat.c: the font bytes plus its pair-kerning table.

    python tools/embed_font.py fonts/Montserrat-Bold.ttf src/gui_font_montserrat.c bold

stb_truetype reads only the legacy 'kern' table, and Montserrat (like most modern fonts) keeps
its kerning in GPOS, so the layout code gets the pairs from here instead. Glyphs 32..255 only,
adjustments in 1/1000 em, sorted by (left, right). Needs fontTools (pip install fonttools).
"""
import sys
from fontTools.ttLib import TTFont

FIRST, LAST = 32, 255


def kern_lookups(gpos):
    ids = []
    for fr in gpos.FeatureList.FeatureRecord:
        if fr.FeatureTag == "kern":
            for i in fr.Feature.LookupListIndex:
                if i not in ids:
                    ids.append(i)
    return sorted(ids)


def pair_subtables(lookup):
    for st in lookup.SubTable:
        if lookup.LookupType == 9:          # extension
            st = st.ExtSubTable
        if st.LookupType == 2 if hasattr(st, "LookupType") else True:
            yield st


def xadv(v):
    return getattr(v, "XAdvance", 0) or 0 if v is not None else 0


def value_for(sts, a, b):
    """The first subtable of one lookup that covers the pair decides it."""
    for st in sts:
        if a not in st.Coverage.glyphs:
            continue
        if st.Format == 1:
            ps = st.PairSet[st.Coverage.glyphs.index(a)]
            for rec in ps.PairValueRecord:
                if rec.SecondGlyph == b:
                    return xadv(rec.Value1)
        elif st.Format == 2:
            c1 = st.ClassDef1.classDefs.get(a, 0)
            c2 = st.ClassDef2.classDefs.get(b, 0)
            return xadv(st.Class1Record[c1].Class2Record[c2].Value1)
    return None


def main():
    src, out, name = sys.argv[1:4]
    data = open(src, "rb").read()
    font = TTFont(src)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    gpos = font["GPOS"].table
    lookups = [gpos.LookupList.Lookup[i] for i in kern_lookups(gpos)]
    subs = [[st for st in pair_subtables(lk)] for lk in lookups]
    chars = [c for c in range(FIRST, LAST + 1) if c in cmap]
    pairs = []
    for a in chars:
        for b in chars:
            total = 0
            for sts in subs:
                v = value_for(sts, cmap[a], cmap[b])
                if v:
                    total += v
            adj = round(total * 1000 / upm)
            if adj:
                pairs.append((a, b, adj))
    pairs.sort()

    lines = [
        f"/* Montserrat {name.capitalize()} 7.200, embedded. Copyright 2011 The Montserrat Project Authors",
        " * (https://github.com/JulietaUla/Montserrat), SIL Open Font License 1.1: see fonts/OFL.txt.",
        f" * Generated by tools/embed_font.py from {src.split('/')[-1]}: the font bytes and its GPOS pair kerning",
        " * (glyphs 32..255, 1/1000 em). Do not edit. */",
        '#include "gui_font_montserrat.h"',
        f"const unsigned char gui_font_montserrat_{name}[] = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines += [
        "};",
        f"const unsigned int gui_font_montserrat_{name}_size = {len(data)};",
        "",
        f"const short gui_font_montserrat_{name}_kern[][3] = {{",
    ]
    for i in range(0, len(pairs), 8):
        lines.append("    " + " ".join("{%d,%d,%d}," % p for p in pairs[i:i + 8]))
    lines += ["};", f"const int gui_font_montserrat_{name}_kern_count = {len(pairs)};", ""]
    open(out, "w", newline="\n").write("\n".join(lines))
    print(f"{len(data)} font bytes, {len(pairs)} kerning pairs -> {out}")


main()
